"""Check that two PDS builds are one physical implementation apart from DRM init data.

The capture image (enrollment) and the production image (binding) must be the
same placed-and-routed design: they may differ only in block-ROM contents,
and only in the key ROM. Compares the routed netlist, the timing netlist with
cell locations and LUT INIT words, and the routed SDF delays.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

# V_DRM36K_E1 /* DRM_106_0 */ #( ...params... ) \inst/name/DRM36K  (
DRM_BLOCK = re.compile(r'(V_DRM\w+\s*/\*\s*\S+\s*\*/\s*#\()(.*?\))(\s*\\?(\S+)\s*\()', re.S)
DRM_INIT = re.compile(r"\.INIT_[0-9A-F]{2}\s*\([^)]*\)")
KEY_ROM = re.compile(r'^key/key_rom')


def strip_date(text):
    text = re.sub(r'\(DATE\s+"[^"]*"\)', '(DATE)', text)
    text = re.sub(r'^// Generated by .*$', '// Generated', text, count=1, flags=re.M)
    # Source-location comments are relative to the build directory, which is
    # one level shallower for build/board than for build/board/ro_capture_*.
    text = re.sub(r'^(\s*//\s*)(?:\.\./)+', r'\1', text, flags=re.M)
    # The opt5 route-check build keeps generated model sources in its snapshot directory.
    return re.sub(r'^(\s*//\s*)(?:rtl/generated|model_snapshot)/mypilot_parameters\.v:',
                  r'\1mypilot_parameters.v:', text, flags=re.M)


def split_drm(text):
    """Return text with DRM init values blanked, and init data per DRM instance."""
    blocks = {}

    def blank(match):
        blocks[match[4]] = hashlib.sha256(''.join(DRM_INIT.findall(match[2])).encode()).hexdigest()
        return match[1] + DRM_INIT.sub('.INIT()', match[2]) + match[3]

    return DRM_BLOCK.sub(blank, text), blocks


def build_files(build):
    base = build / 'prj_tasks/pnr_1'
    return dict(route=base/'place_route/kosmo_training_top_route_optimize.netlist',
                timing_netlist=base/'generate_netlist/kosmo_training_top_sim.v',
                sdf=base/'generate_netlist/kosmo_training_top_sta.sdf')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('capture', type=Path)
    parser.add_argument('production', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    a, b = build_files(args.capture), build_files(args.production)
    result = dict(capture=str(args.capture.resolve()), production=str(args.production.resolve()))
    failures = []
    result['route_netlist_identical'] = a['route'].read_bytes() == b['route'].read_bytes()
    result['sdf_identical_except_date'] = (strip_date(a['sdf'].read_text(encoding='utf-8')) ==
                                           strip_date(b['sdf'].read_text(encoding='utf-8')))
    text_a, drm_a = split_drm(a['timing_netlist'].read_text(encoding='utf-8'))
    text_b, drm_b = split_drm(b['timing_netlist'].read_text(encoding='utf-8'))
    result['timing_netlist_identical_except_drm_init'] = strip_date(text_a) == strip_date(text_b)
    changed = sorted(n for n in drm_a.keys() | drm_b.keys() if drm_a.get(n) != drm_b.get(n))
    result.update(drm_blocks=len(drm_a), drm_init_changed=changed,
                  only_key_rom_changed=all(KEY_ROM.search(n) for n in changed))
    if set(drm_a) != set(drm_b):
        failures.append('DRM instance sets differ')
    if not any(KEY_ROM.search(n) for n in drm_a):
        failures.append('key ROM is not a block RAM; capture and production keys would change logic')
    for key in ('route_netlist_identical', 'sdf_identical_except_date',
                'timing_netlist_identical_except_drm_init', 'only_key_rom_changed'):
        if not result[key]:
            failures.append(key.replace('_', ' ') + ' is false')
    result['same_implementation'] = not failures
    result['failures'] = failures
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(result, indent=2))
    if failures:
        raise SystemExit('Builds are not the same physical implementation: ' + '; '.join(failures))


if __name__ == '__main__':
    main()
