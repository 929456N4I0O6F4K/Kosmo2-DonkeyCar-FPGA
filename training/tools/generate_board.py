"""Generate an isolated PA board project using the supplied Kosmo2 PU wrapper."""
import hashlib
import json
import re
import shutil
from pathlib import Path

root = Path(__file__).resolve().parents[1]
vendor = root.parents[1] / '赛题相关数据kosmo/3. Demo/6.Komos2_PU/block_editor/k100_be/ip_core/k100_be_processing_unit_1_0_0'
dest = root / 'board/vendor'
dest.mkdir(parents=True, exist_ok=True)
manifest = {}
for src in sorted((vendor / 'rtl').glob('*.v')):
    shutil.copy2(src, dest / src.name)
    manifest[src.name] = hashlib.sha256(src.read_bytes()).hexdigest()
template = (vendor / 'k100_be_processing_unit_1_0_0.v').read_text()
instance = template[template.index('system_process_unit #('):]
instance = instance[:instance.rindex('endmodule')]
instance = instance.replace('.P_USE_S_AXI_HP2(0)', '.P_USE_S_AXI_HP2(1)').replace('.P_USE_M_AXI_GP0(1)', '.P_USE_M_AXI_GP0(0)').replace('.P_FCLK_CLK0_BUF(1)', '.P_FCLK_CLK0_BUF(0)')
# Keep vendor tie-offs for all unused ports, expose just SPS2. Inputs previously
# exposed by the demo are tied to zero; no Linux/DDR initialization code is run.
decl = template[:template.index('system_process_unit #(')]
input_names = set(re.findall(r'input\s+(?:\[[^]]+\]\s*)?(\w+)', decl))
output_names = set(re.findall(r'output\s+(?:\[[^]]+\]\s*)?(\w+)', decl))
for name in input_names:
    instance = instance.replace(f'.{name}({name})', f'.{name}(0)')
for name in output_names:
    instance = instance.replace(f'.{name}({name})', f'.{name}()')
ports = '''input wire clk,
 output wire resetn,
 input wire [31:0] awaddr, input wire awvalid, output wire awready,
 input wire [63:0] wdata, input wire [7:0] wstrb, input wire wvalid, output wire wready,
 output wire [1:0] bresp, output wire bvalid, input wire bready,
 input wire [31:0] araddr, input wire arvalid, output wire arready,
 output wire [63:0] rdata, output wire [1:0] rresp, output wire rvalid, input wire rready'''
connections = {'CLK':'clk','RESETN':'resetn','AWADDR':'awaddr','AWVALID':'awvalid','AWREADY':'awready',
 'AWID':"4'd0",'AWLEN':"8'd0",'AWSIZE':"3'd3",'AWBURST':"2'b01",'AWLOCK':"1'b0",'AWCACHE':"4'd0",'AWPROT':"3'd0",'AWQOS':"4'd0",
 'WDATA':'wdata','WSTRB':'wstrb','WVALID':'wvalid','WREADY':'wready','WLAST':"1'b1",'BRESP':'bresp','BVALID':'bvalid','BREADY':'bready',
 'ARADDR':'araddr','ARVALID':'arvalid','ARREADY':'arready','ARID':"4'd0",'ARLEN':"8'd0",'ARSIZE':"3'd3",'ARBURST':"2'b01",'ARLOCK':"1'b0",'ARCACHE':"4'd0",'ARPROT':"3'd0",'ARQOS':"4'd0",
 'RDATA':'rdata','RRESP':'rresp','RVALID':'rvalid','RREADY':'rready'}
for key, value in connections.items():
    instance, n = re.subn(r'\.PU_SPS2_'+key+r'\([^)]*\)', '.PU_SPS2_'+key+'('+value+')', instance)
    assert n == 1, (key, n)
(root/'board/kosmo_pu_sps2.v').write_text('// Generated by tools/generate_board.py; vendor PU IP, SPS2 only.\nmodule kosmo_pu_sps2(\n'+ports+'\n);\n'+instance+'\nendmodule\n')
(dest/'source.json').write_text(json.dumps({'source':str(vendor),'sha256':manifest,'note':'Unmodified generated Pango PU RTL. Vendor license applies.'},indent=2))
fdc=(root.parent/'camera/constraints/camera.fdc').read_text()
fdc=fdc.replace('uart_rx T20 uart_tx U20 ','').replace('rstn uart_rx cam_scl','rstn cam_scl').replace('uart_tx cam_scl','cam_scl')
fdc+='''
foreach {port pin} {pca_scl V10 pca_sda U9} {
 define_attribute p:$port PAP_IO_LOC $pin
 define_attribute p:$port PAP_IO_VCCIO 3.3
 define_attribute p:$port PAP_IO_STANDARD LVCMOS33
}
foreach port {cam_scl cam_sda pca_scl pca_sda} { define_attribute p:$port PAP_IO_BUS_KEEPER PULLUP }
set_false_path -from [get_ports {pca_scl pca_sda}]
set_false_path -to [get_ports {pca_scl pca_sda}]
create_clock -name jtag_tck -period 66.667 [get_pins {dvio/scanchain/TCK_USER}]
set_clock_groups -asynchronous -group [get_clocks jtag_tck] -group [get_clocks sysclk_50] -group [get_clocks cam_pclk]
'''
(root/'board/training.fdc').write_text(fdc)
print('Generated isolated SPS2 wrapper and board constraints; original demo unchanged')
