"""Generate the OV2640 ROM from retained Espressif v2.1.3 sources (Apache-2.0)."""
import ast
import hashlib
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
defs = dict(re.findall(r'^#define\s+(\w+)\s+([^\n]+)', (ROOT/'vendor/ov2640_regs.h').read_text(), re.M))
defs.update(BANK_DSP='0', BANK_SENSOR='1')
ops = {ast.BitOr:lambda a,b:a|b, ast.BitAnd:lambda a,b:a&b, ast.LShift:lambda a,b:a<<b, ast.RShift:lambda a,b:a>>b}
def number(expr):
    def walk(n):
        if isinstance(n, ast.Constant) and isinstance(n.value,int): return n.value
        if isinstance(n, ast.Name): return number(defs[n.id].split('/*')[0])
        if isinstance(n, ast.BinOp) and type(n.op) in ops: return ops[type(n.op)](walk(n.left),walk(n.right))
        if isinstance(n,ast.Call) and isinstance(n.func,ast.Name):
            a=[walk(x) for x in n.args]
            if n.func.id=='COM9_AGC_SET': return 8 | a[0]<<5
            if n.func.id=='VV_AGC_TH_SET': return a[0]<<4 | a[1]&15
        raise ValueError(f'Unsupported expression: {expr}')
    return walk(ast.parse(expr.strip(),mode='eval').body)
def table(name):
    source=(ROOT/'vendor/ov2640_settings.h').read_text()
    body=re.search(r'\b'+name+r'\[\]\[2\]\s*=\s*\{(.*?)\n\};',source,re.S).group(1)
    body=re.sub(r'//[^\n]*|/\*.*?\*/','',body,flags=re.S)
    out=[]
    for entry in re.findall(r'\{([^{}]+)\}',body):
        r,v=map(number,entry.split(',',1))
        if (r,v)==(0,0): break
        out.append((r,v,0))
    return out
def main():
    entries=[(0xff,1,0),(0x12,0x80,10)]+table('ov2640_settings_cif')
    entries += [(0xff,0,0),(0x05,1,0)] + table('ov2640_settings_to_cif')
    # set_framesize(160x120,4:3): CIF source 400x296, offsets zero.
    entries += [(0xff,0,0),(0x51,100,0),(0x52,74,0),(0x53,0,0),
                (0x54,0,0),(0x55,0,0),(0x57,0,0),(0x5a,40,0),(0x5b,30,0),(0x5c,0,0),
                (0xff,1,0),(0x11,3,0),(0x15,0,0),
                (0xff,0,0),(0xd3,8,0),(0x05,0,10)]
    entries += table('ov2640_settings_rgb565')
    entries += [(0xff,1,0),(0x12,0x20,0),(0xff,0,50)]
    color_index=len(entries)-2
    lines=['// Generated by tools/generate_init.py.',
           '// Espressif 2015-2016, Apache-2.0; see vendor/LICENSE.esp32-camera.',
           '`default_nettype none',
           'module ov2640_init_rom(input wire [8:0] index, input wire colorbar,',
           'output reg [7:0] reg_addr, reg_data, delay_ms, output wire last);',
           f"assign last = index >= 9'd{len(entries)};",
           'always @* begin','reg_addr=0; reg_data=0; delay_ms=0;','case(index)']
    for i,(r,v,d) in enumerate(entries):
        value="(colorbar ? 8'h22 : 8'h20)" if i==color_index else f"8'h{v:02x}"
        lines.append(f"9'd{i}: begin reg_addr=8'h{r:02x}; reg_data={value}; delay_ms=8'd{d}; end")
    lines += ['default: begin end','endcase','end','endmodule','`default_nettype wire','']
    (ROOT/'rtl/ov2640_init_rom.v').write_text('\n'.join(lines),encoding='utf-8')
    manifest={'upstream':'espressif/esp32-camera','version':'v2.1.3','width':160,'height':120,
        'format':'RGB565_MSB_FIRST','external_oscillator_hz':'measure on module; upstream reference uses 24 MHz',
        'clkrc':3,'dvp_divider':8,'colorbar_index':color_index,'writes':len(entries),
        'sha256':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((ROOT/'vendor').glob('ov2640*'))},
        'sequence':[{'index':i,'register':f'{r:02x}','value':f'{v:02x}','delay_ms':d} for i,(r,v,d) in enumerate(entries)]}
    (ROOT/'init_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    print(f'Generated {len(entries)} register writes; RGB565 160x120')
if __name__=='__main__': main()

